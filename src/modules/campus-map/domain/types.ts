export type Point = readonly [number, number];
export type Block = 'A' | 'B' | 'C' | 'D' | 'E' | 'F';
export type Floor = 'SE' | 'T' | `${number}`;
export type Bounds = readonly [number, number, number, number];
export type Source = { title: string; url: string };
export type Place = {
  id: string;
  name: string;
  category: string;
  subtitle: string;
  aliases: string;
  building?: string;
  block?: Block;
  floor?: Floor;
  room?: string;
  point: Point;
  coordinate: Point;
  sources: Source[];
};
export type OfficialRoom = {
  code: string;
  block: Block;
  floor: Floor;
  /** Absolute edges x1, y1, x2, y2 in metres (not width/height). */
  bounds: Bounds;
  door: Bounds;
};
export type Entrance = 'metro' | 'sfx';
export type FloorRoom = {
  code: string;
  bounds: Bounds;
  polygon?: Point[];
  door?: Bounds;
  doorPoint?: Point;
  corridorPoint?: Point;
  labelPoint?: Point;
  recorded: boolean;
  certainty: 'official' | 'modeled' | 'zone';
};
type FloorStructure = {
  kind: string;
  bounds: Bounds;
  polygon?: Point[];
  line?: Point[];
};
export type FloorPlan = {
  block: Block;
  floor: Floor;
  rooms: FloorRoom[];
  structures: FloorStructure[];
};
/** Generated by scripts/campus-map/room-model.cjs; pooled across floors. */
export type RoomModel = Omit<FloorRoom, 'code'> & {
  index: number | null;
  route: Point[];
  turn?: 'esquerda' | 'direita';
  side?: 'esquerda' | 'direita';
  ordinal?: number;
  landmark?: string;
  distance?: number;
  towardTip?: boolean;
  atJunction?: boolean;
  towardCultural?: boolean;
  alternatives?: number;
};
type FloorPlanData = {
  block: Block;
  floor: Floor;
  rooms: number[];
  positions: Record<string, number>;
  structures: FloorStructure[];
};
export type MapOrientation = {
  steps: { title: string; detail?: string }[];
  route: Point[];
  routeStart: 'elevators' | 'entrance' | 'stairs';
  endpoint: 'door' | 'modeled-door' | 'zone' | 'block';
  confidence: string;
  floorPlan?: FloorPlan;
  room?: FloorRoom;
  entranceRoute: Point[];
};
export type CampusAtlas = {
  version: string;
  north: number;
  campus: Point[];
  shapes: { id: string; kind: string; rings: Point[][] }[];
  blocks: { id: Block; point: Point; bounds: Bounds; floors: Floor[] }[];
  streets: { name: string; point: Point; angle: number; lines: Point[][] }[];
  paths: Point[][];
  places: Place[];
  rooms: Partial<Record<Block, Partial<Record<Floor, number[]>>>>;
  officialRooms: OfficialRoom[];
  roomModels: RoomModel[];
  floorPlans: FloorPlanData[];
  internalShapes: {
    id: string;
    kind: string;
    block?: Block;
    rings: Point[][];
  }[];
};
export type RoomLocation = {
  kind: 'room';
  building: 'pjlf' | 'haroldinho';
  code: string;
  floor: Floor;
  block?: Block;
};
export type LocationResult =
  | RoomLocation
  | { kind: 'virtual' | 'empty' | 'unknown' }
  | { kind: 'invalid'; message: string };
